// Generates lib/land.ts: a pixel-tile land mask for the spawn map, from Natural Earth (world-atlas).
// One-off; the output is committed so the app has no map dependency at runtime.
// Run: npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1 in some scratch dir, then
//      node scripts/gen-land.mjs <that-dir>/node_modules
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const mods = process.argv[2];
const { feature } = await import(pathToFileURL(join(mods, "topojson-client/src/index.js")));
const { geoContains } = await import(pathToFileURL(join(mods, "d3-geo/src/index.js")));
const topo = JSON.parse(readFileSync(join(mods, "world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const STEP = 2.5; // degrees per tile
const LAT_TOP = 72.5;
const LAT_BOTTOM = -57.5;
const SUB = 3; // 3x3 samples per tile; a tile is land if at least MIN of them are
const MIN = 2;

const rows = [];
for (let lat = LAT_TOP; lat > LAT_BOTTOM; lat -= STEP) {
  let row = "";
  for (let lon = -180; lon < 180; lon += STEP) {
    let hits = 0;
    for (let i = 0; i < SUB; i++)
      for (let j = 0; j < SUB; j++)
        hits += geoContains(land, [lon + ((i + 0.5) * STEP) / SUB, lat - ((j + 0.5) * STEP) / SUB]) ? 1 : 0;
    row += hits >= MIN ? "1" : "0";
  }
  rows.push(row);
}

const out = `// Generated by scripts/gen-land.mjs from Natural Earth 1:50m land (world-atlas). Do not edit.
export const LAND = { step: ${STEP}, latTop: ${LAT_TOP}, lonLeft: -180 } as const;
export const LAND_ROWS: string[] = ${JSON.stringify(rows, null, 0).replace(/","/g, '",\n  "').replace("[", "[\n  ").replace(/]$/, ",\n]")};
`;
writeFileSync(new URL("../lib/land.ts", import.meta.url), out);
console.log(rows.map((r) => r.replace(/0/g, " ").replace(/1/g, "#")).join("\n"));
